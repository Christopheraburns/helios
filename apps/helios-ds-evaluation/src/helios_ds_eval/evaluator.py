"""Evaluation engine for Helios-DS benchmarks.

Compares discovered knowledge (via Helios crawler) against ground-truth records
(generated by Helios-DS generation) to compute precision, recall, and F1 scores.
"""
from datetime import datetime, timezone
from typing import Dict, List, Optional

from .schemas import (
    ACLMetrics,
    ClaimMetrics,
    ComparisonResult,
    DatasetEvaluationResult,
    EntityMetrics,
    RelationshipMetrics,
    ScenarioEvaluationResult,
)


class EvaluationEngine:
    """Compares discovered vs. ground-truth knowledge."""

    def __init__(self, generation_version: str, evaluation_version: str):
        """Initialize evaluator.

        Args:
            generation_version: Version of generator used
            evaluation_version: Version of evaluator
        """
        self.generation_version = generation_version
        self.evaluation_version = evaluation_version

    def compute_entity_metrics(
        self,
        ground_truth_entities: List[Dict],
        discovered_entities: List[Dict],
    ) -> EntityMetrics:
        """Compute entity precision, recall, F1.

        Args:
            ground_truth_entities: Ground-truth entity records
            discovered_entities: Discovered entity records

        Returns:
            EntityMetrics with precision, recall, F1
        """
        total_truth = len(ground_truth_entities)
        total_discovered = len(discovered_entities)

        # Placeholder implementation - in production, would do entity linking
        correct_matches = min(total_discovered, total_truth)

        precision = correct_matches / total_discovered if total_discovered > 0 else 0.0
        recall = correct_matches / total_truth if total_truth > 0 else 0.0

        # F1 score
        if precision + recall > 0:
            f1 = 2 * (precision * recall) / (precision + recall)
        else:
            f1 = 0.0

        return EntityMetrics(
            total_discovered=total_discovered,
            total_ground_truth=total_truth,
            correct_matches=correct_matches,
            precision=precision,
            recall=recall,
            f1_score=f1,
        )

    def compute_relationship_metrics(
        self,
        ground_truth_rels: List[Dict],
        discovered_rels: List[Dict],
    ) -> RelationshipMetrics:
        """Compute relationship precision, recall, F1."""
        total_truth = len(ground_truth_rels)
        total_discovered = len(discovered_rels)

        # Placeholder: simple counting
        correct_matches = min(total_discovered, total_truth)

        precision = correct_matches / total_discovered if total_discovered > 0 else 0.0
        recall = correct_matches / total_truth if total_truth > 0 else 0.0

        if precision + recall > 0:
            f1 = 2 * (precision * recall) / (precision + recall)
        else:
            f1 = 0.0

        return RelationshipMetrics(
            total_discovered=total_discovered,
            total_ground_truth=total_truth,
            correct_matches=correct_matches,
            precision=precision,
            recall=recall,
            f1_score=f1,
        )

    def compute_claim_metrics(
        self,
        ground_truth_claims: List[Dict],
        discovered_claims: List[Dict],
    ) -> ClaimMetrics:
        """Compute claim precision, recall, F1, and truth-status accuracy."""
        total_truth = len(ground_truth_claims)
        total_discovered = len(discovered_claims)

        correct_matches = min(total_discovered, total_truth)

        precision = correct_matches / total_discovered if total_discovered > 0 else 0.0
        recall = correct_matches / total_truth if total_truth > 0 else 0.0

        if precision + recall > 0:
            f1 = 2 * (precision * recall) / (precision + recall)
        else:
            f1 = 0.0

        # Placeholder: truth status accuracy
        truth_status_accuracy = 0.5

        return ClaimMetrics(
            total_discovered=total_discovered,
            total_ground_truth=total_truth,
            correct_matches=correct_matches,
            precision=precision,
            recall=recall,
            f1_score=f1,
            truth_status_accuracy=truth_status_accuracy,
        )

    def compute_acl_metrics(
        self,
        ground_truth_acl: List[Dict],
        discovered_acl: List[Dict],
    ) -> ACLMetrics:
        """Compute ACL/access-control discovery metrics."""
        total_truth_acl = len(ground_truth_acl)
        total_discovered_acl = len(discovered_acl)

        correct_perms = min(total_discovered_acl, total_truth_acl)
        perm_accuracy = correct_perms / total_truth_acl if total_truth_acl > 0 else 0.0

        # Placeholder: principals
        principals_truth = max(1, total_truth_acl)
        principals_discovered = max(1, total_discovered_acl)
        principal_recall = min(1.0, principals_discovered / principals_truth)

        return ACLMetrics(
            total_acl_bindings_ground_truth=total_truth_acl,
            total_acl_bindings_discovered=total_discovered_acl,
            permissions_correct=correct_perms,
            permission_accuracy=perm_accuracy,
            principals_ground_truth=principals_truth,
            principals_discovered=principals_discovered,
            principal_recall=principal_recall,
        )

    def evaluate_scenario(
        self,
        scenario_id: str,
        scenario_type: str,
        ground_truth: Dict,
        discovered: Dict,
    ) -> ScenarioEvaluationResult:
        """Evaluate a single scenario.

        Args:
            scenario_id: Scenario identifier
            scenario_type: Type of scenario
            ground_truth: Ground-truth data from helios_ground_truth.*
            discovered: Discovered data from helios_index.*

        Returns:
            ScenarioEvaluationResult
        """
        entity_metrics = self.compute_entity_metrics(
            ground_truth.get("entities", []),
            discovered.get("entities", []),
        )

        relationship_metrics = self.compute_relationship_metrics(
            ground_truth.get("relationships", []),
            discovered.get("relationships", []),
        )

        claim_metrics = self.compute_claim_metrics(
            ground_truth.get("claims", []),
            discovered.get("claims", []),
        )

        acl_metrics = self.compute_acl_metrics(
            ground_truth.get("acl_bindings", []),
            discovered.get("acl_bindings", []),
        )

        # Compute overall F1 (macro-average)
        f1_scores = [
            entity_metrics.f1_score,
            relationship_metrics.f1_score,
            claim_metrics.f1_score,
        ]
        overall_f1 = sum(f1_scores) / len(f1_scores) if f1_scores else 0.0

        return ScenarioEvaluationResult(
            scenario_id=scenario_id,
            scenario_type=scenario_type,
            entity_metrics=entity_metrics,
            relationship_metrics=relationship_metrics,
            claim_metrics=claim_metrics,
            acl_metrics=acl_metrics,
            overall_f1=overall_f1,
            artifacts_evaluated=len(discovered.get("artifacts", [])),
        )

    def evaluate_dataset(
        self,
        dataset_id: str,
        scenario_results: List[ScenarioEvaluationResult],
    ) -> DatasetEvaluationResult:
        """Aggregate scenario results into dataset evaluation.

        Args:
            dataset_id: Dataset identifier
            scenario_results: Per-scenario evaluation results

        Returns:
            DatasetEvaluationResult
        """
        now = datetime.now(timezone.utc).isoformat()

        if not scenario_results:
            # Empty dataset
            return DatasetEvaluationResult(
                dataset_id=dataset_id,
                generation_version=self.generation_version,
                evaluation_version=self.evaluation_version,
                scenario_results=[],
                macro_entity_f1=0.0,
                macro_relationship_f1=0.0,
                macro_claim_f1=0.0,
                overall_benchmark_score=0.0,
                total_scenarios_evaluated=0,
                total_artifacts_evaluated=0,
                total_entities_ground_truth=0,
                total_relationships_ground_truth=0,
                total_claims_ground_truth=0,
                evaluation_started_at=now,
                evaluation_completed_at=now,
                duration_seconds=0.0,
            )

        # Compute macro-averages
        entity_f1s = [s.entity_metrics.f1_score for s in scenario_results]
        relationship_f1s = [s.relationship_metrics.f1_score for s in scenario_results]
        claim_f1s = [s.claim_metrics.f1_score for s in scenario_results]

        macro_entity_f1 = sum(entity_f1s) / len(entity_f1s) if entity_f1s else 0.0
        macro_relationship_f1 = sum(relationship_f1s) / len(relationship_f1s) if relationship_f1s else 0.0
        macro_claim_f1 = sum(claim_f1s) / len(claim_f1s) if claim_f1s else 0.0

        # Overall benchmark score (simple average of three F1s)
        overall_benchmark_score = (
            macro_entity_f1 + macro_relationship_f1 + macro_claim_f1
        ) / 3.0

        # Aggregate counts
        total_entities = sum(s.entity_metrics.total_ground_truth for s in scenario_results)
        total_relationships = sum(s.relationship_metrics.total_ground_truth for s in scenario_results)
        total_claims = sum(s.claim_metrics.total_ground_truth for s in scenario_results)
        total_artifacts = sum(s.artifacts_evaluated for s in scenario_results)

        return DatasetEvaluationResult(
            dataset_id=dataset_id,
            generation_version=self.generation_version,
            evaluation_version=self.evaluation_version,
            scenario_results=scenario_results,
            macro_entity_f1=macro_entity_f1,
            macro_relationship_f1=macro_relationship_f1,
            macro_claim_f1=macro_claim_f1,
            overall_benchmark_score=overall_benchmark_score,
            total_scenarios_evaluated=len(scenario_results),
            total_artifacts_evaluated=total_artifacts,
            total_entities_ground_truth=total_entities,
            total_relationships_ground_truth=total_relationships,
            total_claims_ground_truth=total_claims,
            evaluation_started_at=now,
            evaluation_completed_at=now,
            duration_seconds=0.0,
        )
